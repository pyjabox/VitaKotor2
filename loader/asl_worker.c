/* asl_worker.c -- ASLgl, gles2-bc and vitaGL on the GL worker (ASLW).
 *
 * The GL worker (gl_worker.c) runs vitaGL on core 2; everything above it --
 * Aspyr's ASLgl, its KOTOR shader path (GlesKotorSetupShader, KotorProgram)
 * and gles2-bc -- ran on the game thread: 11-18 ms a frame in busy scenes
 * (hardware probe, 2026-10-16, asl_probe.c). ASLgl and gles2-bc cannot be
 * split -- the shader setup reads gles2-bc's matrix stacks on every draw -- so
 * the game thread now records the engine's calls into ASLgl, and the worker
 * runs them (docs/specs/GL_ASL_WORKER.md):
 *
 *  - every ASLgl function slot holds a recorder (aslw_gen.c, generated by
 *    tools/gen_aslw.py, or one of the aslw_custom_* below). On the worker --
 *    ASLgl calling itself -- or with ASLW off, it calls through;
 *  - most calls are recorded and the game thread carries on; calls that
 *    return a value or write through a pointer make it wait for the worker
 *    (SYNC), which must not happen in steady frames. The queries the engine
 *    makes every frame are answered from copies kept here: the viewport, the
 *    framebuffer and texture bindings, blend factors, enables, the current
 *    colour, which program names exist, glGetError;
 *  - vertex arrays in client memory are copied when a draw is recorded, and
 *    the worker points ASLgl at the copies for that draw (1-3 draws a frame);
 *  - four engine globals ASLgl reads at program bind and draw time
 *    (g_illumShader, g_illumShaderValues, g_useDistortionOutput,
 *    s_vertexShaderParams; 40 bytes in all) would be read late: ASLgl's five
 *    loads of their addresses are redirected to private copies, which the
 *    recorder refreshes before a bind or draw whenever the engine's values
 *    changed.
 *
 * ux0:data/kotor2/aslw_mode.txt: 0 off (nothing installed), 1 on, a on and off
 * alternately every 10 s (the worker drained and ASLgl handed back to the game
 * thread in between). Without the file: ASLW_DEFAULT. With the GL worker in its
 * inline mode (glw_mode.txt 1), every call is recorded and replayed at once on
 * the game thread: the stream format, checked without threads. */

