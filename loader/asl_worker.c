/* A client array the next draw reads: on, and set while no buffer was bound. */
static int arr_client(const carr_t *c) { return c->on && c->set && !c->buf && c->ptr; }
static uint32_t arr_eff(const carr_t *c) { return c->stride ? c->stride : c->size * aslw_type_size(c->type); }
static int any_client(void) {
  for (int i = 0; i < NARR; i++) if (arr_client(&m_arr[i])) return 1;
  /* A texcoord array enabled while the client unit was unknown cannot be
   * placed: treat as client, so the draw waits rather than read a stale one. */
  return 0;
}

/* Copies of the client arrays for vertices [first, first + count), and the
 * worker pointed at them; arr_restore() records the way back after the draw.
 * 0: none to copy; -1: too much (the draw waits for the worker instead). */
static int s_snap_idx[NARR], s_snap_n;
static int arr_snapshot(uint32_t first, uint32_t count) {
  uint32_t bytes = 0;
  s_snap_n = 0;
  for (int i = 0; i < NARR; i++) {
    const carr_t *c = &m_arr[i];
    if (!arr_client(c)) continue;
    uint32_t len = count ? (count - 1) * arr_eff(c) + c->size * aslw_type_size(c->type) : 0;
    bytes += (len + 3) & ~3u;
    s_snap_idx[s_snap_n++] = i;
  }
  if (!s_snap_n) return 0;
  if (!count) { s_snap_n = 0; return 0; }
  if (bytes > ASLW_INLINE_MAX) { s_snap_n = 0; return -1; }
  uint32_t nw = 3 + 8u * (uint32_t)s_snap_n;
  uint32_t *a = glw_begin(ASLW_OP_CUSTOM + OP_ARR_SET, nw, bytes);
  a[0] = (uint32_t)s_snap_n;
  a[1] = m_client_known ? m_client_active : 0;
  a[2] = m_array_buf;
  uint32_t off = nw;
  for (int j = 0; j < s_snap_n; j++) {
    const carr_t *c = &m_arr[s_snap_idx[j]];
    uint32_t eff = arr_eff(c), len = (count - 1) * eff + c->size * aslw_type_size(c->type);
    uint32_t *r = a + 3 + 8 * j;
    r[0] = (uint32_t)s_snap_idx[j]; r[1] = (uint32_t)c->fn; r[2] = c->size; r[3] = c->type; r[4] = c->stride;
    r[5] = c->norm; r[6] = off; r[7] = first * eff;
    memcpy(a + off, (const uint8_t *)c->ptr + (size_t)first * eff, len);
    off += (len + 3) / 4;
  }
  glw_end(a);
  w_arr_draws++;
  w_arr_bytes += bytes;
  return s_snap_n;
}
static void arr_restore(void) {
  if (!s_snap_n) return;
  uint32_t *b = glw_begin(ASLW_OP_CUSTOM + OP_ARR_RESTORE, 3 + 7u * (uint32_t)s_snap_n, 0);
  b[0] = (uint32_t)s_snap_n;
  b[1] = m_client_known ? m_client_active : 0;
  b[2] = m_array_buf;
  for (int j = 0; j < s_snap_n; j++) {
    const carr_t *c = &m_arr[s_snap_idx[j]];
    uint32_t *r = b + 3 + 7 * j;
    r[0] = (uint32_t)s_snap_idx[j]; r[1] = (uint32_t)c->fn; r[2] = c->size; r[3] = c->type; r[4] = c->stride;
    r[5] = c->norm; r[6] = (uint32_t)c->ptr;
  }
  glw_end(b);
  s_snap_n = 0;
}

static uint32_t max_index(uintptr_t idx, uint32_t count, uint32_t type) {
  uint32_t mx = 0;
  for (uint32_t i = 0; i < count; i++) {
    uint32_t v = type == 0x1403 ? ((const uint16_t *)idx)[i] :
                 type == 0x1405 ? ((const uint32_t *)idx)[i] : ((const uint8_t *)idx)[i];
    if (v > mx) mx = v;
  }
  return mx;
}

/* A draw that cannot be recorded with copies runs while the game thread
 * waits: the worker reads the client memory in place. */
static void draw_sync(int idx, const uint32_t *w, uint32_t n) {
  w_sync_draws++;
  uint32_t *a = glw_begin((ASLW_OP_BASE + (uint32_t)idx) | GLW_SYNC, n, 0);
  memcpy(a, w, n * 4);
  (void)glw_sync(a);
}

static void draw_range(int idx, const uint32_t *w, uint32_t n, uint32_t first, uint32_t count) {
  globals_check();
  int k = arr_snapshot(first, count);
  if (k < 0) { draw_sync(idx, w, n); return; }
  record_raw(idx, w, n);
  arr_restore();
}

void aslw_custom_glDrawArrays(uint32_t mode, uint32_t first, uint32_t count) {
  if (!recording()) { aslw_gen_glDrawArrays(mode, first, count); return; }
  uint32_t w[3] = {mode, first, count};
  draw_range(i_drawa, w, 3, first, count);
}
void aslw_custom_ASLglDrawQuadArrays(uint32_t count) {
  if (!recording()) { aslw_gen_ASLglDrawQuadArrays(count); return; }
  uint32_t w[1] = {count};
  draw_range(i_quads, w, 1, 0, count);
}
void aslw_custom_ASLglDrawQuadArraysStartIndex(uint32_t first, uint32_t count) {
  if (!recording()) { aslw_gen_ASLglDrawQuadArraysStartIndex(first, count); return; }
  uint32_t w[2] = {first, count};
  draw_range(i_quads_si, w, 2, first, count);
}
void aslw_custom_glDrawElements(uint32_t mode, uint32_t count, uint32_t type, uintptr_t indices) {
  if (!recording()) { aslw_gen_glDrawElements(mode, count, type, indices); return; }
  globals_check();
  int client_idx = !m_elem_buf && indices;
  uint32_t w[4] = {mode, count, type, (uint32_t)indices};
  if (any_client()) {
    if (!client_idx || !m_bufs_known) { draw_sync(i_drawe, w, 4); return; }   /* range unknown */
    if (arr_snapshot(0, max_index(indices, count, type) + 1) < 0) { draw_sync(i_drawe, w, 4); return; }
  }
  if (client_idx && count) {
    uint32_t isz = aslw_type_size(type), bytes = count * isz;
    if (bytes > ASLW_INLINE_MAX) { arr_restore(); draw_sync(i_drawe, w, 4); return; }
    uint32_t *a = glw_begin(ASLW_OP_CUSTOM + OP_DRAW_E_CLIENT, 3, bytes);
    a[0] = mode; a[1] = count; a[2] = type;
    memcpy(a + 3, (const void *)indices, bytes);
    glw_end(a);
  } else {
    record_raw(i_drawe, w, 4);
  }
  arr_restore();
}
void aslw_custom_glEnd(void) {
  if (recording()) globals_check();
  aslw_gen_glEnd();
}

/* ---- the worker -------------------------------------------------------------------- */
static void set_array(uint32_t arr, int fn, uint32_t size, uint32_t type, uint32_t stride, uint32_t norm,
                      uintptr_t p) {
  void *f = orig_of(fn);
  if (!f) return;
  if (arr >= A_ATTR0) {
    ((void (*)(uint32_t, uint32_t, uint32_t, uint32_t, uint32_t, uintptr_t))f)(arr - A_ATTR0, size, type, norm,
                                                                               stride, p);
  } else if (arr == A_NORMAL) {
    ((void (*)(uint32_t, uint32_t, uintptr_t))f)(type, stride, p);
  } else {
    if (arr >= A_TEX0) ((void (*)(uint32_t))orig_of(i_cat))(0x84C0 + arr - A_TEX0);
    ((void (*)(uint32_t, uint32_t, uint32_t, uintptr_t))f)(size, type, stride, p);
  }
}

void aslw_execute(uint32_t op, int sync, const uint32_t *a, uint32_t *ret) {
  if (op < ASLW_OP_CUSTOM - ASLW_OP_BASE) { aslw_replay_gen(op, sync, a, ret); return; }
  switch (op - (ASLW_OP_CUSTOM - ASLW_OP_BASE)) {
    case OP_GLOBALS:
      memcpy(g_private, a, GLB_BYTES);
      break;
    case OP_ARR_SET: case OP_ARR_RESTORE: {
      /* Client arrays (set with no buffer bound): a pointer given while the
       * draw's array buffer is bound would be taken as an offset into it. */
      int restore = op - (ASLW_OP_CUSTOM - ASLW_OP_BASE) == OP_ARR_RESTORE;
      uint32_t n = a[0], tex = 0;
      void (*bind)(uint32_t, uint32_t) = (void (*)(uint32_t, uint32_t))orig_of(i_bindarb >= 0 ? i_bindarb : i_bind);
      if (a[2] && bind) bind(0x8892, 0);
      for (uint32_t j = 0; j < n; j++) {
        const uint32_t *r = restore ? a + 3 + 7 * j : a + 3 + 8 * j;
        uintptr_t p = restore ? (uintptr_t)r[6] : (uintptr_t)((const uint8_t *)(a + r[6]) - r[7]);
        if (r[0] >= A_TEX0 && r[0] < A_ATTR0) tex = 1;
        set_array(r[0], (int)r[1], r[2], r[3], r[4], r[5], p);
      }
      if (a[2] && bind) bind(0x8892, a[2]);
      if (tex && i_cat >= 0) ((void (*)(uint32_t))orig_of(i_cat))(0x84C0 + a[1]);
      break;
    }
    case OP_DRAW_E_CLIENT:
      ((void (*)(uint32_t, uint32_t, uint32_t, uintptr_t))orig_of(i_drawe))(a[0], a[1], a[2], (uintptr_t)(a + 3));
      break;
    case OP_NOP:
      break;
    case OP_CALL:
      ((void (*)(uint32_t))(uintptr_t)a[0])(a[1]);
      break;
    case OP_RESYNC:
      glw_resync();
      break;
    default:
      log_printf("[aslw] FATAL: unknown op %u", (unsigned)op);
      break;
  }
}

void aslw_note_sync(uint32_t op) {
  if (op < 512) w_sync_by[op]++;
}

/* ---- loader code that works with ASLgl's GL state ------------------------------------ */
void aslw_run(void (*fn)(uint32_t), uint32_t arg) {
  if (!s_installed || !recording()) { fn(arg); return; }
  uint32_t *a = glw_begin(ASLW_OP_CUSTOM + OP_CALL, 2, 0);
  a[0] = (uint32_t)(uintptr_t)fn;
  a[1] = arg;
  glw_end(a);
}

void *aslw_entry(const char *mangled, void *fallback) {
  if (!s_installed) return fallback;
  for (unsigned i = 0; i < aslw_nfns; i++)
    if (!strcmp(aslw_fns[i].mangled, mangled) && *aslw_fns[i].orig)
      return aslw_fns[i].custom ? aslw_fns[i].custom : aslw_fns[i].gen;
  return fallback;
}

int aslw_phase(void) { return !s_installed ? -1 : aslw_direct_flag ? 0 : 1; }
int64_t aslw_window_age_us(void) {
  return s_installed && w_t0 ? (int64_t)(sceKernelGetProcessTimeWide() - w_t0) : -1;
}

/* ---- on and off -------------------------------------------------------------------- */
/* Hand ASLgl back to the game thread: the worker finishes what was recorded
 * first, and ASLgl's loads go back to the engine's own globals. */
static void go_direct(void) {
  if (aslw_direct_flag) return;
  /* The worker finishes, then reads vitaGL's state into the GL worker's
   * copy, which ASLgl's calls went past while it ran there. */
  uint32_t *a = glw_begin((ASLW_OP_CUSTOM + OP_RESYNC) | GLW_SYNC, 0, 0);
  (void)glw_sync(a);
  globals_patch(0);
  aslw_direct_flag = 1;
  glw_aslw_active(0);
}
static void go_worker(void) {
  if (!aslw_direct_flag) return;
  memcpy(g_private, (const void *)g_base, GLB_BYTES);
  memcpy(g_sent, (const void *)g_base, GLB_BYTES);
  g_sent_valid = 1;
  globals_patch(1);
  glw_aslw_active(1);
  __sync_synchronize();
  aslw_direct_flag = 0;
}

void aslw_on_swap(void) {
  if (!s_installed) return;
  uint64_t now = sceKernelGetProcessTimeWide();
  if (w_prev) {
    uint64_t d = now - w_prev;
    w_frame_us += d;
    w_frames++;
    if (d > 250000) aslw_forget();               /* a load: the loader drew on its own */
  }
  w_prev = now;
  if (!w_t0) { w_t0 = now; return; }
  if (now - w_t0 < 10000000u) return;
  unsigned f = w_frames ? w_frames : 1;
  char syncs[300], qs[300];
  int n = 0, m = 0;
  syncs[0] = qs[0] = 0;
  for (int k = 0; k < 8; k++) {
    int best = -1;
    for (unsigned i = 0; i < aslw_nfns && i < 512; i++)
      if (w_sync_by[i] && (best < 0 || w_sync_by[i] > w_sync_by[best])) best = (int)i;
    if (best < 0 || n > (int)sizeof syncs - 48) break;
    n += snprintf(syncs + n, sizeof syncs - (size_t)n, " %s:%.2f", aslw_fns[best].name,
                  (double)w_sync_by[best] / f);
    w_sync_by[best] = 0;
  }
  for (int i = 0; i < 24 && w_q[i].n && m < (int)sizeof qs - 48; i++)
    m += snprintf(qs + m, sizeof qs - (size_t)m, " %s(0x%x):%.2f", aslw_fns[w_q[i].fn].name,
                  (unsigned)w_q[i].pname, (double)w_q[i].n / f);
  log_printf("[aslw] %s%u frames, %.1f ms | answered %.1f a frame, asked the worker %.2f; dropped repeats %.0f; "
             "globals sent %.2f; client-array draws %.2f (%.0f bytes), waited-for draws %.2f, uploads of unknown layout %u%s",
             s_ab ? (aslw_direct_flag ? "OFF " : "ON ") : "", (unsigned)w_frames,
             w_frames ? (double)w_frame_us / w_frames / 1000.0 : 0.0, (double)w_answer / f, (double)w_sync_q / f,
             (double)w_drop / f, (double)w_globals / f, (double)w_arr_draws / f, (double)w_arr_bytes / f,
             (double)w_sync_draws / f, (unsigned)w_unknown_px, ASLW_VERIFY ? "" : "");
  if (n || m) log_printf("[aslw] waits a frame:%s | queries asked:%s", n ? syncs : " none", m ? qs : " none");
#if ASLW_VERIFY
  log_printf("[aslw] VERIFY: %u answers checked, %u disagreed", (unsigned)w_verify, (unsigned)w_mismatch);
#endif
  memset(w_sync_by, 0, sizeof w_sync_by);
  memset(w_q, 0, sizeof w_q);
  w_frames = 0;
  w_frame_us = 0;
  w_drop = w_answer = w_sync_q = w_globals = w_arr_draws = w_arr_bytes = w_sync_draws = w_verify = w_mismatch = 0;
  w_unknown_px = 0;
  w_t0 = now;
  if (s_ab) {
    s_ab_on = !s_ab_on;
    if (s_ab_on) go_worker(); else go_direct();
  }
}

/* ---- install -------------------------------------------------------------------- */
static void patch(uintptr_t *slot, uintptr_t v) { kuKernelCpuUnrestrictedMemcpy(slot, &v, sizeof v); }

void aslw_install(void) {
  char c = ASLW_DEFAULT;
  SceUID fd = sceIoOpen(DATA_PATH "/aslw_mode.txt", SCE_O_RDONLY, 0);
  if (fd >= 0) {
    char b = 0;
    if (sceIoRead(fd, &b, 1) == 1) c = b;
    sceIoClose(fd);
  }
  if (c != '1' && c != 'a') {
    log_printf("[aslw] off (aslw_mode '%c'): ASLgl runs on the game thread", c);
    return;
  }
  if (gl_worker_mode() == 0) {
    log_printf("[aslw] off: the GL worker is off");
    return;
  }
  s_mode = 1;
  s_ab = c == 'a';
  g_ok = globals_setup();
  if (!g_ok) {
    log_printf("[aslw] DISABLED: the shared globals do not match this libkotor2");
    return;
  }
  i_getiv = fn_index("glGetIntegerv"); i_getfv = fn_index("glGetFloatv"); i_isen = fn_index("glIsEnabled");
  i_isprog = fn_index("glIsProgramARB");
  i_vertexp = fn_index("glVertexPointer"); i_colorp = fn_index("glColorPointer");
  i_normalp = fn_index("glNormalPointer"); i_texp = fn_index("glTexCoordPointer");
  i_secp = fn_index("glSecondaryColorPointer"); i_attrp = fn_index("glVertexAttribPointer");
  i_attrparb = fn_index("glVertexAttribPointerARB"); i_cat = fn_index("glClientActiveTextureARB");
  i_drawe = fn_index("glDrawElements"); i_drawa = fn_index("glDrawArrays");
  i_quads = fn_index("ASLglDrawQuadArrays"); i_quads_si = fn_index("ASLglDrawQuadArraysStartIndex");
  i_bind = fn_index("glBindBuffer"); i_bindarb = fn_index("glBindBufferARB");
  if (i_drawe < 0 || i_drawa < 0 || i_vertexp < 0 || i_texp < 0 || i_cat < 0) {
    log_printf("[aslw] DISABLED: draw or array functions missing");
    return;
  }

  /* Every slot of every ASLgl function: the recorder; the original is what
   * the PLT slot held (a loader hook on it stays in the chain). */
  unsigned slots = 0, fns = 0, custom = 0;
  for (unsigned f = 0; f < aslw_nfns; f++) {
    const aslw_fn_t *e = &aslw_fns[f];
    uintptr_t *list[8];
    int nl = 0;
    uintptr_t plt_val = 0;
    for (int i = 0; i < kotor_mod.num_reldyn + kotor_mod.num_relplt && nl < 8; i++) {
      Elf32_Rel *rel = i < kotor_mod.num_reldyn ? &kotor_mod.reldyn[i] : &kotor_mod.relplt[i - kotor_mod.num_reldyn];
      unsigned type = ELF32_R_TYPE(rel->r_info);
      if (type != R_ARM_ABS32 && type != R_ARM_GLOB_DAT && type != R_ARM_JUMP_SLOT) continue;
      if (strcmp(kotor_mod.dynstr + kotor_mod.dynsym[ELF32_R_SYM(rel->r_info)].st_name, e->mangled)) continue;
      uintptr_t *slot = (uintptr_t *)(kotor_mod.text_base + rel->r_offset);
      if (type == R_ARM_JUMP_SLOT || !plt_val) plt_val = *slot;
      list[nl++] = slot;
    }
    if (!nl) continue;
    *e->orig = (void *)plt_val;
    uintptr_t rec = (uintptr_t)(e->custom ? e->custom : e->gen);
    for (int j = 0; j < nl; j++) patch(list[j], rec);
    slots += (unsigned)nl;
    fns++;
    if (e->custom) custom++;
  }
  aslw_direct_flag = 0;
  globals_patch(1);
  glw_aslw_active(1);
  s_installed = 1;
  log_printf("[aslw] armed: %u ASLgl functions (%u custom), %u slots; GL worker mode %d%s%s", fns, custom, slots,
             gl_worker_mode(), s_ab ? "; A/B: ASLgl on the worker and on the game thread, alternately every 10 s" : "",
             ASLW_VERIFY ? "; VERIFY: answers checked against the worker" : "");
}

