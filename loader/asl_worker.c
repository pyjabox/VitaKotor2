/* ASLgl passes it to vitaGL as is (gles2-bc tail-calls glPixelStorei); the
 * loader's mip-chain hook reads the alignment back through vitaGL. */
/* The unpack state the engine set, for the sizes of the pixels it uploads
 * (glPixelStore is never compiled into a display list). */
static uint32_t m_unpack_align = 4, m_unpack_other;   /* other: row length, skips, swap, lsb set */
static uint32_t m_unpack_v[8];
void aslw_custom_glPixelStorei(uint32_t pname, uint32_t v) {
  if (engine()) {
    if (pname == 0x0CF5) {                                        /* UNPACK_ALIGNMENT */
      m_unpack_align = v;
      if (note()) glw_note_unpack(v);
    } else if (pname >= 0x0CF0 && pname <= 0x0CF4) {              /* SWAP_BYTES .. SKIP_PIXELS */
      m_unpack_v[pname - 0x0CF0] = v;
      m_unpack_other = 0;
      for (int i = 0; i < 5; i++) m_unpack_other |= m_unpack_v[i];
    }
  }
  aslw_gen_glPixelStorei(pname, v);
}

/* Bytes the engine's pixels take for a w x h upload, as GL reads them;
 * ASLW_SIZE_UNKNOWN for a layout this does not follow (the upload then runs
 * with the game thread waiting, reading the memory in place). */
uint32_t aslw_pixels_size(uint32_t w, uint32_t h, uint32_t format, uint32_t type) {
  uint32_t comps, bpp;
  switch (format) {
    case 0x1908: case 0x80E1: comps = 4; break;                   /* RGBA, BGRA */
    case 0x1907: case 0x80E0: comps = 3; break;                   /* RGB, BGR */
    case 0x190A: case 0x8227: comps = 2; break;                   /* LUMINANCE_ALPHA, RG */
    case 0x1906: case 0x1909: case 0x1903: case 0x1904: case 0x1905: case 0x1902:
      comps = 1; break;                                           /* ALPHA, LUMINANCE, RED..BLUE, DEPTH */
    default: comps = 0; break;
  }
  switch (type) {
    case 0x1400: case 0x1401: bpp = comps; break;                 /* BYTE, UNSIGNED_BYTE */
    case 0x1402: case 0x1403: case 0x140B: bpp = comps * 2; break;   /* SHORT, USHORT, HALF_FLOAT */
    case 0x1404: case 0x1405: case 0x1406: bpp = comps * 4; break;   /* INT, UINT, FLOAT */
    case 0x8032: case 0x8362: bpp = comps ? 1 : 0; break;         /* 3_3_2 and REV */
    case 0x8033: case 0x8034: case 0x8363: case 0x8364: case 0x8365: case 0x8366:
      bpp = comps ? 2 : 0; break;                                 /* 4444, 5551, 565 and REVs */
    case 0x8035: case 0x8036: case 0x8367: case 0x8368: bpp = comps ? 4 : 0; break;   /* 8888, 1010102, REVs */
    default: bpp = 0; break;
  }
  uint32_t a = m_unpack_align;
  if (!bpp || m_unpack_other || (a != 1 && a != 2 && a != 4 && a != 8) || (int32_t)w <= 0 || (int32_t)h <= 0) {
    if ((int32_t)w > 0 && (int32_t)h > 0) {
      w_unknown_px++;
      static unsigned logged;
      if (logged++ < 8)
        log_printf("[aslw] pixels of an unknown layout (format 0x%x, type 0x%x, %ux%u, alignment %u, other unpack "
                   "state %s): the upload waits for the worker", (unsigned)format, (unsigned)type, (unsigned)w,
                   (unsigned)h, (unsigned)a, m_unpack_other ? "set" : "none");
    }
    return (int32_t)w <= 0 || (int32_t)h <= 0 ? 0 : ASLW_SIZE_UNKNOWN;
  }
  uint32_t row = w * bpp, pitch = (row + a - 1) / a * a;
  return pitch * (h - 1) + row;
}

void aslw_custom_glViewport(uint32_t x, uint32_t y, uint32_t w, uint32_t h) {
  if (engine() && !m_compiling) {
    m_vp[0] = (int32_t)x; m_vp[1] = (int32_t)y; m_vp[2] = (int32_t)w; m_vp[3] = (int32_t)h;
    m_vp_known = 1;
    if (note()) glw_note_rect(1, (int32_t)x, (int32_t)y, (int32_t)w, (int32_t)h);
  }
  aslw_gen_glViewport(x, y, w, h);
}
void aslw_custom_glScissor(uint32_t x, uint32_t y, uint32_t w, uint32_t h) {
  if (note() && !m_compiling) glw_note_rect(0, (int32_t)x, (int32_t)y, (int32_t)w, (int32_t)h);
  aslw_gen_glScissor(x, y, w, h);
}
void aslw_custom_glBindFramebufferEXT(uint32_t target, uint32_t fb) {
  if (note() && !m_compiling) glw_note_fb(target == 0x8D40 ? 0x8D40 : target, fb);   /* FRAMEBUFFER */
  aslw_gen_glBindFramebufferEXT(target, fb);
}
void aslw_custom_glBindTexture(uint32_t target, uint32_t tex) {
  if (engine() && !m_compiling && target == 0x0DE1 && m_active_known) {
    m_tex2d[m_active] = tex;
    m_tex2d_known[m_active] = 1;
  }
  aslw_gen_glBindTexture(target, tex);
}
